  /* Deterministic shuffle (mulberry32 + Fisher-Yates) so that every student
     sees the same split, and so a metric that moves when you drag a slider
     moved because of the slider. */
  function shuffled(seed) {
    var a = REVIEWS.slice(), s = seed >>> 0;
    function rnd() {
      s = (s + 0x6D2B79F5) >>> 0;
      var t = Math.imul(s ^ (s >>> 15), 1 | s);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    }
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(rnd() * (i + 1));
      var tmp = a[i]; a[i] = a[j]; a[j] = tmp;
    }
    return a;
  }

  root.CADC_REVIEWS = REVIEWS;
  root.CADC_REVIEWS_SHUFFLED = shuffled;
